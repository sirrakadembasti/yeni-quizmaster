import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { QueryClient, QueryClientProvider, QueryObserver } from '@tanstack/react-query';
const state = vi.hoisted(() => ({ user: { id: 'a', name: 'User', role: 'student' }, get: vi.fn(), save: vi.fn(), toast: vi.fn() }));
vi.mock('@/context/auth-context', () => ({ useAuth: () => ({ user: state.user, updateUser: vi.fn() }) }));
vi.mock('@/hooks/use-toast', () => ({ useToast: () => ({ toast: state.toast }) }));
vi.mock('@/components/layout/DashboardLayout', () => ({ DashboardLayout: ({ children }: any) => <div>{children}</div> }));
vi.mock('wouter', () => ({ useLocation: () => ['', vi.fn()], useSearch: () => '?tab=notifications' }));
vi.mock('@/lib/api', () => ({ authApi: {}, adminApi: {}, notificationApi: { getUserNotifications: async () => ({ notifications: [] }), getPreferences: async () => ({ muted: false }), updatePreferences: async () => ({ muted: true }) } }));
vi.mock('@/lib/versioned-notification-preferences', async importOriginal => ({ ...await importOriginal<any>(), getVersionedNotificationPreferences: state.get, saveVersionedNotificationPreferences: state.save }));
import Settings from '@/pages/settings';
let client: QueryClient;
beforeEach(() => {
  vi.clearAllMocks(); state.user = { id: 'a', name: 'User', role: 'student' };
  state.get.mockResolvedValue({ muted: false, revision: 0 });
  client = new QueryClient({ defaultOptions: { queries: { retry: false }, mutations: { retry: false } } });
});
afterEach(() => { cleanup(); client.clear(); });
const page = () => <QueryClientProvider client={client}><Settings /></QueryClientProvider>;
it('does not send a queued command using a different user session', async () => {
  let release!: () => void;
  vi.spyOn(client, 'cancelQueries').mockImplementation(() => new Promise<void>(resolve => { release = resolve; }));
  const view = render(page()); const toggle = await screen.findByRole('switch');
  await waitFor(() => expect(toggle).toBeEnabled()); fireEvent.click(toggle);
  await waitFor(() => expect(client.cancelQueries).toHaveBeenCalled());
  state.user = { id: 'b', name: 'Other', role: 'student' }; view.rerender(page());
  await act(async () => release());
  expect(state.save).not.toHaveBeenCalled();
  expect(state.toast).not.toHaveBeenCalled();
});
it('reconciles the shared sound preference after same-user navigation', async () => {
  let finish!: (result: any) => void;
  state.save.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const view = render(page()); const toggle = await screen.findByRole('switch');
  await waitFor(() => expect(toggle).toBeEnabled()); fireEvent.click(toggle);
  await waitFor(() => expect(state.save).toHaveBeenCalled());
  const observer = new QueryObserver(client, { queryKey: ['notifications', 'preferences', 'versioned', 'a'], queryFn: state.get });
  const unsubscribe = observer.subscribe(() => {});
  view.unmount();
  state.get.mockResolvedValue({ muted: true, revision: 1 });
  await act(async () => finish({ preferences: { muted: true, revision: 1 }, saved: true }));
  await waitFor(() => expect(client.getQueryData(['notifications', 'preferences', 'versioned', 'a'])).toEqual({ muted: true, revision: 1 }));
  unsubscribe();
  expect(state.toast).not.toHaveBeenCalled();
});
it('does not cache another account reconciliation after A to B to A', async () => {
  let finish!: (result: any) => void;
  state.save.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const view = render(page()); const toggle = await screen.findByRole('switch');
  await waitFor(() => expect(toggle).toBeEnabled()); fireEvent.click(toggle);
  await waitFor(() => expect(state.save).toHaveBeenCalled());
  state.user = { id: 'b', name: 'Other', role: 'student' }; view.rerender(page());
  state.user = { id: 'a', name: 'User', role: 'student' }; view.rerender(page());
  await act(async () => finish({ preferences: { muted: true, revision: 99 }, saved: false }));
  await waitFor(() => expect(client.getQueryData(['notifications', 'preferences', 'versioned', 'a'])).toEqual({ muted: false, revision: 0 }));
  expect(state.toast).not.toHaveBeenCalled();
});
it('disables repeat actions and uses durable reconciliation after an ambiguous write', async () => {
  let finish!: (result: any) => void;
  state.save.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  render(page()); const toggle = await screen.findByRole('switch');
  await waitFor(() => expect(toggle).toBeEnabled()); fireEvent.click(toggle);
  await waitFor(() => expect(toggle).toBeDisabled());
  expect(state.save).toHaveBeenCalledWith(true, 0);
  await act(async () => finish({ preferences: { muted: true, revision: 1 }, saved: false }));
  await waitFor(() => expect(toggle).not.toBeChecked());
  expect(state.toast).toHaveBeenCalledWith(expect.objectContaining({ variant: 'destructive' }));
});
it('ignores callbacks from a previous user', async () => {
  let finish!: (result: any) => void;
  state.save.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const view = render(page()); const toggle = await screen.findByRole('switch');
  await waitFor(() => expect(toggle).toBeEnabled()); fireEvent.click(toggle);
  await waitFor(() => expect(state.save).toHaveBeenCalled());
  state.user = { id: 'b', name: 'Other', role: 'student' }; view.rerender(page());
  await waitFor(() => expect(client.getQueryData(['notifications', 'preferences', 'versioned', 'b'])).toEqual({ muted: false, revision: 0 }));
  await act(async () => finish({ preferences: { muted: true, revision: 1 }, saved: true }));
  expect(client.getQueryData(['notifications', 'preferences', 'versioned', 'b'])).toEqual({ muted: false, revision: 0 });
  expect(state.toast).not.toHaveBeenCalled();
});
it('does not replace a newer durable preference with an older completed write', async () => {
  let finish!: (result: any) => void;
  state.save.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  render(page()); const toggle = await screen.findByRole('switch');
  await waitFor(() => expect(toggle).toBeEnabled()); fireEvent.click(toggle);
  await waitFor(() => expect(state.save).toHaveBeenCalled());
  await act(async () => client.setQueryData(['notifications', 'preferences', 'versioned', 'a'], { muted: false, revision: 2 }));
  await act(async () => finish({ preferences: { muted: true, revision: 1 }, saved: true }));
  expect(client.getQueryData(['notifications', 'preferences', 'versioned', 'a'])).toEqual({ muted: false, revision: 2 });
  expect(toggle).toBeChecked();
  expect(state.toast).not.toHaveBeenCalled();
});
