import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { assertIsolatedRuntime, prisma, login, api } from './academic-archive-helpers';
import { captureArchive } from '../server/services/archive-capture';

test('administrator recovers the same frozen manual archive and the real worker closes the blocked year once', async ({ page }) => {
  test.setTimeout(120000);
  const runtime = assertIsolatedRuntime(), db = prisma(), errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    const admin = await db.user.findUniqueOrThrow({ where: { email: 'academic-admin@example.test' } });
    const active = await db.academicYear.findFirstOrThrow({ where: { status: 'active' } });
    // Keep automatic annual enqueue disabled until the complete failed manual fixture is ready.
    const year = await db.academicYear.update({ where: { id: active.id }, data: { label: '2025-2026', opensAt: new Date('2025-09-01'), scheduledCloseAt: new Date('2099-07-14T21:05:00Z') } });
    const teacher = await db.user.create({ data: { name: 'Recovery fixture teacher', email: randomUUID() + '@example.test', password: 'synthetic', role: 'teacher' } });
    const cls = await db.class.create({ data: { name: 'Recovery graduation class' } });
    const student = await db.user.create({ data: { name: 'Recovery frozen student', email: randomUUID() + '@example.test', password: 'synthetic', role: 'student', classId: cls.id, studentNo: 1 } });
    const quiz = await db.quiz.create({ data: { title: 'Recovery frozen exam', createdBy: teacher.id, status: 'published', assignedClasses: { connect: { id: cls.id } } } });
    await db.studentResult.create({ data: { studentId: student.id, quizId: quiz.id, score: 85, status: 'completed' } });
    await db.academicTransitionRule.create({ data: { yearId: year.id, fromClassId: cls.id, graduate: true } });
    const owner = 'recovery-fixture-' + randomUUID();
    const manual = await db.archiveSnapshot.create({ data: { academicYearId: year.id, label: year.label, mode: 'manual', scopeJson: JSON.stringify({ quizIds: [quiz.id] }), initiatedBy: admin.id, leaseOwner: owner, leaseExpiresAt: new Date(Date.now() + 180000) } });
    await captureArchive(db, manual.id, { owner, now: () => new Date() });
    const frozen = await db.archiveSnapshotRow.findMany({ where: { snapshotId: manual.id }, orderBy: { id: 'asc' } });
    const target = path.join(runtime.root, 'artifacts', year.label, manual.id);
    await mkdir(target, { recursive: true });
    await writeFile(path.join(target, 'archive.zip'), 'Synthetic corrupt incomplete published package');
    await db.archiveSnapshot.update({ where: { id: manual.id }, data: { status: 'failed', attempts: 20, leaseOwner: null, leaseExpiresAt: null, lastError: 'Archive ZIP verification failed' } });
    const empty = await db.archiveSnapshot.create({ data: { academicYearId: year.id, label: year.label, mode: 'manual', status: 'failed', attempts: 20, scopeJson: JSON.stringify({ quizIds: [randomUUID()] }), initiatedBy: admin.id, lastError: 'Selected content is missing' } });
    await db.academicYear.update({ where: { id: year.id }, data: { scheduledCloseAt: new Date('2026-07-14T21:05:00Z') } });
    await login(page);
    await expect.poll(async () => (await db.archiveSnapshot.findUnique({ where: { annualKey: year.label } }))?.status, { timeout: 25000 }).toBe('queued');
    const annual = await db.archiveSnapshot.findUniqueOrThrow({ where: { annualKey: year.label } });
    await page.goto('/archive', { waitUntil: 'domcontentloaded' });
    await page.getByRole('tab', { name: 'Yıl Sonu', exact: true }).click();
    await expect(page.getByText(`İş ${manual.id}:`, { exact: false })).toContainText('Yeniden Dene');
    await page.getByRole('button', { name: `İşi Aç: ${manual.id}`, exact: true }).click();
    const detail = page.getByRole('region', { name: 'Seçilen arşiv işi', exact: true });
    await expect(detail.getByRole('button', { name: `Yeniden Dene: ${manual.id}`, exact: true })).toBeEnabled();
    await expect(detail.getByRole('button', { name: `Kopyalama başlamadan iptal: ${manual.id}`, exact: true })).toHaveCount(0);
    expect((await db.user.findUniqueOrThrow({ where: { id: student.id } })).isActive).toBe(true);
    expect(await db.academicYear.count()).toBe(1);
    await page.getByRole('tab', { name: 'Geçmiş ve İşler', exact: true }).click();
    const cancel = page.getByRole('button', { name: 'Kopyalama başlamadan iptal', exact: true });
    await expect(cancel).toHaveCount(1);
    await cancel.click();
    await expect(page.getByRole('status').filter({ hasText: 'Kopyalama başlamadan arşiv iptal edildi' })).toBeVisible();
    expect((await db.archiveSnapshot.findUniqueOrThrow({ where: { id: empty.id } })).status).toBe('cancelled');
    expect(await db.archiveSnapshotRow.count({ where: { snapshotId: empty.id } })).toBe(0);
    expect(await db.actionLog.count({ where: { action: 'ARCHIVE_CANCELLED', details: { contains: empty.id } } })).toBe(1);
    expect((await db.archiveSnapshot.findUniqueOrThrow({ where: { id: annual.id } })).status).toBe('queued');
    const recovery = page.getByRole('button', { name: 'Yeniden Dene', exact: true });
    await expect(recovery).toHaveCount(1);
    await expect(recovery).toBeEnabled();
    await page.getByRole('tab', { name: 'Yıl Sonu', exact: true }).click();
    await page.getByRole('button', { name: `İşi Aç: ${manual.id}`, exact: true }).click();
    await detail.getByRole('button', { name: `Yeniden Dene: ${manual.id}`, exact: true }).click();
    await expect(page.getByRole('status').filter({ hasText: 'kuyruğa alındı' })).toBeVisible();
    const quarantineRoot = path.join(runtime.root, 'artifacts', '.quarantine');
    const quarantines = await readdir(quarantineRoot);
    expect(quarantines).toHaveLength(1);
    const quarantined = path.join(quarantineRoot, quarantines[0]);
    expect(await readFile(path.join(quarantined, 'package', 'archive.zip'), 'utf8')).toBe('Synthetic corrupt incomplete published package');
    expect(JSON.parse(await readFile(path.join(quarantined, 'reason.json'), 'utf8'))).toMatchObject({ snapshotId: manual.id, reason: 'artifact_integrity_failed' });
    await expect.poll(async () => (await db.archiveSnapshot.findUniqueOrThrow({ where: { id: manual.id } })).status, { timeout: 45000 }).toBe('completed');
    expect(await db.archiveSnapshotRow.findMany({ where: { snapshotId: manual.id }, orderBy: { id: 'asc' } })).toEqual(frozen);
    await expect.poll(async () => (await db.archiveSnapshot.findUniqueOrThrow({ where: { id: annual.id } })).status, { timeout: 45000 }).toBe('completed');
    expect(await db.archiveSnapshot.count({ where: { annualKey: year.label } })).toBe(1);
    expect(await db.academicYear.count()).toBe(2);
    expect(await db.user.findUniqueOrThrow({ where: { id: student.id } })).toMatchObject({ isActive: false, classId: null, graduationYear: year.label });
    const logs = await db.actionLog.findMany({ where: { details: { contains: manual.id } } });
    const recoveryLog = logs.find(log => log.action === 'ARCHIVE_RECOVERY_REQUESTED');
    expect(JSON.parse(recoveryLog!.details!)).toMatchObject({ previousAttempts: 20 });
    expect(logs.filter(log => log.action === 'ARCHIVE_COMPLETED')).toHaveLength(1);
    const automatic = await db.actionLog.findFirstOrThrow({ where: { action: 'ARCHIVE_CREATED', details: { contains: annual.id } } });
    expect(JSON.parse(automatic.details!)).toMatchObject({ automatic: true });
    // Completed packages stay immutable through recovery, even if an external change corrupts them.
    const completed = await db.archiveSnapshot.findUniqueOrThrow({ where: { id: manual.id } });
    await writeFile(completed.artifactPath!, 'Synthetic tampered completed ZIP');
    expect((await api(page, 'POST', `/admin/archive/jobs/${manual.id}/retry`)).status()).toBe(409);
    expect(await readFile(completed.artifactPath!, 'utf8')).toBe('Synthetic tampered completed ZIP');
    expect(await db.archiveSnapshot.findUniqueOrThrow({ where: { id: manual.id } })).toEqual(completed);
    const yearsResponse = await api(page, 'GET', '/admin/archive/years');
    expect(yearsResponse.status()).toBe(200);
    const history = await api(page, 'GET', `/admin/academic-history/years/${year.id}/rows?type=student&studentId=${student.id}`);
    expect(history.status()).toBe(200);
    expect((await history.json()).rows[0]).toMatchObject({ name: 'Recovery frozen student', className: 'Recovery graduation class', isActive: true });
    expect(errors).toEqual([]);
  } finally { await db.$disconnect(); }
});
