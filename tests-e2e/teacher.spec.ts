import { test, expect } from '@playwright/test';

test.describe('Teacher Flow', () => {
  // Using the seeded admin/teacher from prisma seed or we can just try to login as a known user
  // For the sake of E2E, assuming an existing teacher or admin creates a teacher.
  // We'll mock the flow or assume a seeded teacher: teacher@example.com / password123

  test.beforeEach(async ({ page }) => {
    await page.goto('/auth');
    await page.getByLabel(/e-posta/i).fill('teacher@example.com');
    await page.getByLabel(/şifre/i).fill('password123'); // Assuming default seed password
    await page.getByRole('button', { name: /giriş yap/i }).click();
    
    // Wait for dashboard
    await page.waitForURL('**/dashboard**', { timeout: 10000 }).catch(() => {});
  });

  test('should create a quiz and assign it', async ({ page }) => {
    // Navigate to create quiz
    await page.goto('/quizzes');
    await page.getByRole('button', { name: /sınav oluştur/i }).click();

    // Fill quiz details
    await page.getByLabel(/başlık/i).fill('Playwright E2E Quiz');
    await page.getByLabel(/açıklama/i).fill('This is a test quiz generated by Playwright');
    
    await page.getByRole('button', { name: /kaydet/i }).click();

    // Verify creation success
    await expect(page.locator('text=Sınav başarıyla oluşturuldu').first()).toBeVisible({ timeout: 10000 });

    // Navigate to quiz details to add questions
    await page.getByText('Playwright E2E Quiz').first().click();
    
    // Add question
    await page.getByRole('button', { name: /soru ekle/i }).click();
    await page.getByLabel(/soru metni/i).fill('What is 2 + 2?');
    // Assuming options inputs are accessible by role or placeholder
    const optionsInputs = page.getByPlaceholder(/seçenek/i);
    if (await optionsInputs.count() >= 2) {
      await optionsInputs.nth(0).fill('3');
      await optionsInputs.nth(1).fill('4');
    }
    
    // Select correct answer (often a radio button next to the option)
    const radios = page.getByRole('radio');
    if (await radios.count() > 1) {
      await radios.nth(1).check();
    }

    await page.getByRole('button', { name: /kaydet/i }).first().click();
    await expect(page.locator('text=Sorular başarıyla güncellendi').first()).toBeVisible({ timeout: 10000 });
  });
});