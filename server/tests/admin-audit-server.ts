import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { PrismaClient } from '@prisma/client';
import bcrypt from 'bcryptjs';
const require = createRequire(import.meta.url);
const repo = resolve(import.meta.dirname, '../..');
const root = mkdtempSync(join(repo, 'server/data/quizmaster-test-admin-audit-'));
for (const dir of ['server/data','server/uploads','client']) mkdirSync(join(root,dir),{recursive:true});
for (const dir of ['server','client']) writeFileSync(join(root,dir,'package.json'),'{}');
const db = join(root,'server/data/audit.db');
writeFileSync(db,'');
process.env.DATABASE_URL='file:'+db.replaceAll('\\','/');
process.env.SESSION_SECRET='isolated-admin-audit-only-secret-2026';
process.env.PORT='5510'; process.env.HOST='127.0.0.1';
process.env.FRONTEND_URL='http://127.0.0.1:5511';
process.env.ALLOWED_ORIGINS='http://127.0.0.1:5511';
process.env.NODE_ENV='development';
process.env.ALLOW_RUNTIME_DEPLOYMENT_CHANGES='true';
for (const key of ['EMAIL_USER','EMAIL_PASS','EMAIL_FROM','GEMINI_API_KEY','OPENAI_API_KEY','APP_BASE_PATH','FORCE_SECURE_COOKIES']) delete process.env[key];
execFileSync(process.execPath,[require.resolve('prisma/build/index.js'),'migrate','deploy','--schema',join(repo,'server/prisma/schema.prisma')],{env:process.env,stdio:'pipe'});
const p=new PrismaClient();
const password=await bcrypt.hash('AuditOnly2026!',10);
const admin=await p.user.create({data:{id:'audit-admin',name:'Audit Admin',email:'audit-admin@example.test',password,role:'admin'}});
const teacher=await p.user.create({data:{id:'audit-teacher',name:'Audit Teacher',email:'audit-teacher@example.test',password,role:'teacher'}});
const category=await p.category.create({data:{id:'audit-category',name:'Audit Mathematics'}});
const cls=await p.class.create({data:{id:'audit-class',name:'Audit 7A',classTeacher:{connect:{id:teacher.id}},assignedCategories:{connect:{id:category.id}},teachers:{connect:{id:teacher.id}}}});
const student=await p.user.create({data:{id:'audit-student',name:'Audit Student',email:'audit-student@example.test',password,role:'student',classId:cls.id,studentNo:1}});
const parent=await p.user.create({data:{id:'audit-parent',name:'Audit Parent',email:'audit-parent@example.test',password,role:'parent',guardianLinks:{create:{studentId:student.id,relation:'Anne'}}}});
for (const [id,creator,type,status] of [['audit-exam',admin.id,'exam','draft'],['audit-teacher-exam',teacher.id,'exam','published'],['audit-survey',admin.id,'survey','published']]) {
await p.quiz.create({data:{id,title:id,createdBy:creator,contentType:type,status,categoryId:category.id,assignedClasses:{connect:{id:cls.id}},questions:{create:{id:id+'-q',text:'Audit question?',type:type==='survey'?'short-answer':'multiple-choice',options:type==='survey'?null:JSON.stringify(['A','B','C','D']),correctAnswer:type==='survey'?null:'A',order:0}}}});
}
await p.studentResult.create({data:{id:'audit-result',studentId:student.id,quizId:'audit-teacher-exam',status:'completed',score:100,totalQuestions:1,correctAnswersCount:1,completedAt:new Date(),submittedAt:new Date(),answers:JSON.stringify({'audit-teacher-exam-q':'A'})}});
await p.surveySubmission.create({data:{surveyId:'audit-survey',studentId:student.id,answers:{create:{questionId:'audit-survey-q',value:'Audit response'}}}});
await p.announcement.create({data:{id:'audit-announcement',title:'Audit announcement',content:'Isolated audit content',createdBy:admin.id,targetRole:'all'}});
await p.$disconnect();
writeFileSync(join(repo,'tests/denetim-kanitlari/yonetici/runtime.json'),JSON.stringify({root,database:db,ports:[5510,5511]},null,2));
process.chdir(root);
console.log('ISOLATED AUDIT ROOT '+root);
await import('../index');
